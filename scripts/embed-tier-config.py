#!/usr/bin/env python3
"""Generate tier_config.h: runtime headers and build flags for the native tier.

The CLI may run outside the source tree, so the headers that emitted C
includes are embedded. The file is rewritten only when its content changes.
"""
import hashlib, json, sys
from pathlib import Path


def c_string(text):
    return json.dumps(text)  # JSON escapes are valid C string escapes here


def main():
    out, cc, host_flags, *files = sys.argv[1:]
    # Files after '--' only contribute to the ABI digest (the emitter sources).
    headers, digest_only = (files[:files.index('--')], files[files.index('--') + 1:]) if '--' in files else (files, [])
    digest = hashlib.sha256()
    for name in digest_only:
        digest.update(Path(name).name.encode() + b'\0' + Path(name).read_bytes() + b'\0')
    parts = ['/* Generated by scripts/embed-tier-config.py. */',
             '#define RC_TIER_DEFAULT_CC ' + c_string(cc),
             '#define RC_TIER_HOST_FLAGS ' + c_string(' '.join(host_flags.split())),
             '#ifndef RC_TIER_DEFAULT_THRESHOLD',
             '#define RC_TIER_DEFAULT_THRESHOLD 1000',
             '#endif',
             'static const struct { const char *name, *text; } rc_tier_headers[] = {']
    for header in headers:
        text = Path(header).read_text()
        digest.update(Path(header).name.encode() + b'\0' + text.encode() + b'\0')
        parts.append('  {%s, %s},' % (c_string(Path(header).name), c_string(text)))
    parts.append('};')
    parts.append('#define RC_TIER_HEADER_DIGEST ' + c_string(digest.hexdigest()))
    content = '\n'.join(parts) + '\n'
    path = Path(out)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


if __name__ == '__main__':
    main()
